# 答案：
# 关于劳动仲裁要多久，参考法条里能找到的时间规定如下：
# **一、申请仲裁的期限**
# 提出仲裁要求的一方，应当自劳动争议发生之日起六十日内向劳动争议仲裁委员会提出书面申请[1]。也就是说，你得在劳动争议发生后60天内去申请仲裁，超过这个时间再申请，可能就不被受理了[1]。
# **二、仲裁裁决作出的期限**
# 仲裁裁决一般应在收到仲裁申请的六十日内作出[1]。也就是说，仲裁委员会从收到你的申请开始算，一般要在60天内给出裁决结果[1]。
# **三、受理后送达和答辩的时间**
# 劳动争议仲裁委员会受理仲裁申请后，应当在五日内将仲裁申请书副本送达被申请人[5]。被申请人收到副本后，应当在十日内提交答辩书；仲裁委员会收到答辩书后，应当在五日内将答辩书副本送达申请人[5]。被申请人没提交答辩书的，不影响仲裁程序进行[5]。
# **四、仲裁庭的组成方式**
# 劳动争议仲裁委员会裁决案件实行仲裁庭制，仲裁庭由三名仲裁员组成，设首席仲裁员；简单的劳动争议案件可以由一名仲裁员独任仲裁[3]。这一条没有直接规定天数，但说明简单案件程序上可以更快一些[3]。
# **总结一下：** 你需要在劳动争议发生后60天内申请仲裁[1]；仲裁委员会一般要在收到申请后60天内作出裁决[1]；受理后5天内送达申请书副本，被申请人10天内提交答辩书，仲裁委员会收到答辩书后5天内送达副本[5]。
# 至于从申请到最终拿到裁决之间具体每一天怎么算、有没有延长的情况，参考法条里没有更多规定，未找到相关依据，建议咨询专业律师。
