# [10 拖欠工资找谁]
# 参考答案：劳动保障监察条例 第9条
# 检索到：
# [1] 保障农民工工资支付条例第四十九条
# [2] 保障农民工工资支付条例第五十条
# [3] 保障农民工工资支付条例第十条
# [4] 中华人民共和国劳动争议调解仲裁法第九条
# [5] 保障农民工工资支付条例第七条
# 答案：
# 被拖欠工资，你可以向人力资源社会保障行政部门投诉，也可以申请劳动争议调解仲裁或者提起诉讼[3]。也就是说，你可以去劳动保障部门举报投诉，也可以走仲裁或打官司的路子来要回工资[3]。
# 任何单位和个人对拖欠农民工工资的行为，都有权向人力资源社会保障行政部门或者其他有关部门举报[3]。也就是说，不只是你自己，别人看到了也可以帮你举报[3]。
# 人力资源社会保障行政部门和其他有关部门应当公开举报投诉电话、网站等渠道，依法接受对拖欠农民工工资行为的举报、投诉[3]。也就是说，这些部门必须把投诉电话和网站公开出来，方便你找到他们[3]。
# 对于举报、投诉的处理实行首问负责制，属于本部门受理的，应当依法及时处理；不属于本部门受理的，应当及时转送相关部门，相关部门应当依法及时处理，并将处理结果告知举报、投诉人[3]。也就是说，你找到哪个部门，他们就得管；不归他们管的，他们要帮你转给该管的部门，而且最后要把处理结果告诉你[3]。
# 用人单位违反国家规定，拖欠或者未足额支付劳动报酬的，劳动者可以向劳动行政部门投诉，劳动行政部门应当依法处理[4]。也就是说，单位拖欠工资，你找劳动行政部门投诉，他们必须依法处理[4]。
# 人力资源社会保障行政部门负责保障农民工工资支付工作的组织协调、管理指导和农民工工资支付情况的监督检查，查处有关拖欠农民工工资案件[5]。也就是说，拖欠工资的案件主要由人社部门来查处[5]。
# 住房城乡建设、交通运输、水利等相关行业工程建设主管部门按照职责履行行业监管责任，督办因违法发包、转包、违法分包、挂靠、拖欠工程款等导致的拖欠农民工工资案件[5]。也就是说，如果是在建筑、交通、水利这些工地上干活被欠工资，相关行业主管部门也有责任督办[5]。
# 公安机关负责及时受理、侦办涉嫌拒不支付劳动报酬刑事案件[5]。也就是说，如果欠薪情节严重涉嫌犯罪，公安机关会管[5]。
# 另外，农民工与用人单位就拖欠工资存在争议，用人单位应当提供依法由其保存的劳动合同、职工名册、工资支付台账和清单等材料；不提供的，依法承担不利后果[2]。也就是说，打官司或仲裁时，单位得拿出合同、名册、工资台账这些材料，拿不出来就对单位不利[2]。
