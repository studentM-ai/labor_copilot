# [8 女员工怀孕能被辞退吗]
# 参考答案：女职工劳动保护特别规定 第5条
# 检索到：
# [1] 女职工劳动保护特别规定第五条
# [2] 女职工劳动保护特别规定第七条
# [3] 中华人民共和国劳动法第六十一条
