# [5] 最高人民法院关于审理劳动争议案件适用法律问题的解释（一）第四十四条
# 答案：
# 不能因为怀孕就辞退女员工[1]。用人单位不得因女职工怀孕、生育、哺乳降低其工资、予以辞退、与其解除劳动或者聘用合同[1]。也就是说，公司不能拿"你怀孕了"当理由开除你或者跟你解约[1]。
# 如果公司真的做出了辞退等决定，发生争议时，是由用人单位来举证证明自己的决定有道理，而不是让员工自己去证明[5]。简单说，打官司时公司得拿出证据说明辞退合法，拿不出来就要承担不利后果[5]。
# 另外补充一点：怀孕期间公司还不能安排你干重体力劳动或孕期禁忌的工作，怀孕七个月以上还不能安排加班和夜班[3][4]。但这些是保护性规定，核心结论还是那句——不能仅因怀孕辞退你[1]。
