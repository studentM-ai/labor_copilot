# 检测到：拒答 / 建议咨询

# [6 工伤怎么认定]
# 参考答案：工伤保险条例 第14条
# 检索到：
# [1] 工伤保险条例第二十条
# [2] 工伤保险条例第十八条
# [3] 工伤保险条例第五十七条
