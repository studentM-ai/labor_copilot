# [4 加班费怎么算]
# 参考答案：劳动法 第44条
# 检索到：
# [1] 中华人民共和国劳动合同法第三十一条
# [2] 最高人民法院关于审理劳动争议案件适用法律问题的解释（一）第四十二条
# [3] 中华人民共和国劳动合同法第八十五条
# [4] 关于工资总额组成的规定第九条
# [5] 最高人民法院关于审理劳动争议案件适用法律问题的解释（一）第三十五条
# 答案：
# 关于加班费怎么算，参考法条里没有给出具体的计算公式（比如按工资的百分之多少算），只规定了以下内容：
# **1. 单位安排加班就必须付加班费**
# 用人单位安排加班的，应当按照国家有关规定向劳动者支付加班费[1]。也就是说，只要是单位安排你加班，就得给钱，不能白干[1]。
# **2. 加班费属于工资的一部分**
# 加班加点工资是指按规定支付的加班工资和加点工资[4]。也就是说，加班费是工资总额的组成部分，不是单位可给可不给的“福利”[4]。
# **3. 单位不付加班费会有什么后果**
# 安排加班不支付加班费的，由劳动行政部门责令限期支付；逾期不支付的，责令用人单位按应付金额百分之五十以上百分之一百以下的标准向劳动者加付赔偿金[3]。也就是说，单位拖着不给，你可以向劳动行政部门投诉，单位除了补付加班费，还可能被要求额外赔你50%到100%[3]。
# **4. 想要加班费，你得先证明加了班**
# 劳动者主张加班费的，应当就加班事实的存在承担举证责任；但如果你有证据证明单位掌握加班事实的证据，单位不提供的，由单位承担不利后果[2]。也就是说，你得先拿出加班的证据（比如打卡记录、工作群消息等）；如果证据在单位手里而单位不拿出来，后果由单位承担[2]。
# **5. 离职时签的加班费结算协议一般有效**
# 劳动者与单位就支付加班费等达成的协议，不违反法律强制性规定、不存在欺诈胁迫等情形的，应当认定有效；但存在重大误解或显失公平的，可以请求法院撤销[5]。也就是说，离职时如果签了“加班费已结清”之类的协议，一般是算数的，除非你能证明签的时候被坑了或者明显不公平[5]。
# **具体按工资的几倍计算，参考法条里没有规定，未找到相关依据，建议咨询专业律师。**
