# [5] 中华人民共和国劳动合同法第二十三条
# 答案：
# 公司让你签竞业协议，本身是可以的，但有几个前提条件需要满足。
# 首先，公司只能和"负有保密义务的劳动者"约定竞业限制条款[5]。也就是说，不是随便什么岗位都能让你签竞业协议，得是你在工作中会接触到公司的商业秘密或与知识产权相关的保密事项才行[5]。如果你只是个普通岗位，接触不到什么秘密，公司让你签这个协议的合理性就存疑。
# 其次，签了竞业协议后，公司在你离职后的竞业限制期限内，必须按月给你经济补偿[5]。不是让你光承担义务不给钱的。如果公司约定了竞业限制和经济补偿，你离职后履行了竞业限制义务，你可以要求公司支付经济补偿[3]。
# 另外，如果因为公司的原因，导致离职后三个月都没给你发经济补偿，你可以请求解除竞业限制约定[4]。也就是说，公司光让你签协议却不给钱，你是有权要求解除的。
# 总结一下：签竞业协议本身不违法，但公司得满足"你负有保密义务"这个前提[5]，而且离职后得按月给你经济补偿[5]。如果公司三个月不给你补偿，你可以要求解除[4]。
# 至于你具体岗位是否属于"负有保密义务"的范围、协议条款是否合理，这些需要结合你的实际情况判断，建议咨询专业律师。
