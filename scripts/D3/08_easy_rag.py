# 答案：
# 关于工伤认定的问题，根据参考法条，可以从以下几个方面来理解：
# **一、申请工伤认定需要提交哪些材料？**
# 提出工伤认定申请，需要提交三类材料：一是工伤认定申请表；二是能证明你和用人单位存在劳动关系的材料（包括事实劳动关系）；三是医疗诊断证明或者职业病诊断证明书（或职业病诊断鉴定书）[2]。简单说，就是要填一张申请表、证明你确实在这个单位干活、再加上医院开的诊断证明，三样缺一不可[2]。申请表里要写清楚事故发生的时间、地点、原因以及你的受伤程度等基本情况[2]。
# **二、材料不齐怎么办？**
# 如果你提交的材料不完整，社会保险行政部门应当一次性书面告知你需要补正的全部材料，不能让你来回跑[2]。你按照书面告知的要求补齐材料后，社会保险行政部门就应当受理[2]。
# **三、多久能出认定结果？**
# 社会保险行政部门应当自受理申请之日起60日内作出工伤认定决定，并书面通知你（或你的近亲属）和所在单位[1]。如果事实清楚、权利义务明确，应当在15日内作出决定[1]。也就是说，一般情况下最多等60天，情况简单的15天就能出结果[1]。另外，如果认定需要以司法机关或有关行政主管部门的结论为依据，在那些部门还没出结论期间，认定时限会中止[1]。
# **四、对认定结果不服怎么办？**
# 如果你或你的近亲属、或者所在单位对工伤认定申请不予受理的决定不服，或者对工伤认定结论不服，可以依法申请行政复议，也可以依法向人民法院提起行政诉讼[4]。简单说，就是觉得结果不对，可以找上级部门复议，也可以直接去法院告[4]。
# **五、行政部门工作人员有问题怎么办？**
# 如果社会保险行政部门工作人员无正当理由不受理工伤认定申请，或者弄虚作假把不符合条件的人认定为工伤，或者未妥善保管证据材料导致证据灭失，或者收受当事人财物，会依法给予处分，情节严重构成犯罪的还要追究刑事责任[3]。另外，工作人员与申请人有利害关系的，应当回避[1]。
# **六、提供虚假材料的后果**
# 如果申请人或用人单位隐瞒有关情况或提供虚假材料，导致工伤认定错误，社会保险行政部门可以在诉讼中依法予以更正[5]。
