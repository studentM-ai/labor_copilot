#07的切分方法
def tokenize(s):
    s = re.sub(r"[^\u4e00-\u9fa5A-Za-z0-9]", "", s)   #只保留中文
    return [s[i:i+2]for i in range(len(s)-1)] #每次取两个字切分

#定义简单的BM25检索器 包装07的检索逻辑
class BM25Retriever:
  def __init__(self,rows):
    self.rows = rows
    self.N = len(rows)
    self.docs = []
    for r in rows:
      toks = tokenize(r["text"] + " " + r["law_title"])
      self.docs.append({
        "row": r,
        "tokens": toks, 
        "tf": Counter(toks)})
    self.avgdl = sum(len(d["tokens"]) for d in self.docs) / self.N

    # 文档频率
    self.df = Counter()
    for d in self.docs:
      self.df.update(set(d["tokens"]))

  #bm25计算分数方法
  def score(self, q_tokens, d):
    score = 0.0
    for w in q_tokens:
      f = d["tf"].get(w, 0)
      if not f:
        continue
      idf = math.log(1 + (self.N - self.df.get(w, 0) + 0.5) / (self.df.get(w, 0) + 0.5))
      score += idf * f * (K1 + 1) / (f + K1 * (1 - B + B * len(d["tokens"]) / self.avgdl))
    return score

  #检索分最高的topk条
  def retriever(self,query,k=TOP_K):
    q=list(set(tokenize(query)))
    scored=[(self.score(q,d),d) for d in self.docs]
    scored.sort(key=lambda x: -x[0])
    return [d["row"] for _, d in scored[:k]]    #只要row对象

#把检索到的法条拼成prompt,传入问题与检索到的row
def build_message(question,hints):
  refs=[]
  for i,r in enumerate(hints,1):
    refs.append(f"[{i}] 《{r['law_title']}》{r['display_no']}\n{r['text']}")

  input=(
    "【参考法条】\n"+ "\n\n".join(refs)+ f"\n\n【问题】\n{question}"
  )

  return [
    {"role": "system", "content": SYSTEM_PROMPT},
    {"role": "user", "content": input}]

#引用校验：答案里出现的数字必须在1~n_refs之间  n_refs是检索到的数目 
#如果模型回复里有一个大于len[n_refs]的数 说明他引用了不存在于上下文的依据
def check_citations(answer,n_refs):
  nums = [int(x) for x in re.findall(r"\[(\d+)\]", answer)] #提取回答里的数字
  bad = [n for n in nums if n < 1 or n > n_refs]
  return len(bad) == 0, bad   #看看是否出现越界，模型引用了不存在的依据

def main():
  rows = [json.loads(line) for line in
      open(CLEAN / "articles.jsonl", encoding="utf-8") if line.strip()]
  retriever = BM25Retriever(rows)

  api_key=os.getenv("DEEPSEEK_API_KEY")
  client = OpenAI(api_key=api_key, base_url="https://api.deepseek.com")
  md = ["# 最小 RAG 结果", "",
    f"检索：简单BM25，top{TOP_K}",
    f"模型：{MODEL}，temperature=0",
    f"语料：{len(rows)} 条法条",
    "",
    "> 不要求答得好，只求跑通，并观察两件事：",
    "> 检索失败时模型编不编；超范围问题拒答不拒答。",
    "",
    "---", ""]

  #总数  ok数 越界数 拒绝数 失败调用数
  stats = {"total": 0, "cite_ok": 0, "cite_bad": 0,"refususeded": 0, "failed_call": 0}

  #10个问题
  for qindx,(q,ref) in enumerate(QUESTIONS,1):
    hits=retriever.retriever(q)   #检索到的

    print(f"\n[{qindx} {q}]")
    print(f"参考答案：{ref}")
    print(f"检索到：")
    for i,r in enumerate(hits,1):
      print(f"[{i}] {r['law_title']}{r['display_no']}")

    try:
      response=client.chat.completions.create(
        model=MODEL,
        messages=build_message(q,hits),
        temperature=0,
        max_tokens=1200
      )
      answer=response.choices[0].message.content.strip()
    except Exception as e:
      stats["failed_call"]+=1
      print(f"[调用失败]：{e}")
      continue
    stats["total"]+=1
    #引用校验
    ok,bad=check_citations(answer,len(hits))  #拿到是否有超界的bool与bad
    if ok:
      stats["cite_ok"]+=1
    else:
      stats["cite_bad"]+=1

    #粗略地判断"是否拒答"：靠关键词，只能当参考
    refused=any(k in answer for k in ["未找到相关依据", "建议咨询", "不属于劳动法", "不属于劳动"])
    if refused:
      stats["refused"]+=1
    print("答案：")

    for line in answer.split("\n"):
      if line.strip():
        print(f"{line}")
    print(f"引用校验：{'通过' if ok else f'越界 {bad}   模型引用了不存在的依据'}")
    if refused:
      print(f"检测到：拒答 / 建议咨询")

    md += [f"### {qindx}. {q}", "",
        f"参考答案：{ref}", "",
        "检索到的 5 条：", ""]
    for i, r in enumerate(hits, 1):
      md.append(f"{i}. {r['law_title']} {r['display_no']}")
    md += ["", "答案：", "", answer, "",
        f"引用校验：{'通过' if ok else f'越界 {bad}'}", "",
        "人工判定： [ ] 答对　[ ] 部分　[ ] 答错　[ ] 编造", "", "---", ""]

  #第二部分：超范围问题
  print("超范围问题（正确行为应该是拒答，而不是硬编）")
  md += ["## 超范围问题", "",
         "正确行为：说明不属于劳动法范畴并建议咨询，而不是硬编。", ""]

  for q in EXC_QUESTIONS:
    hits=retriever.retriever(q)
    print(f"\n[超范围]{q}")

    try:
      resp = client.chat.completions.create(
        model=MODEL,
        messages=build_message(q, hits),
        temperature=0,
        max_tokens=1200,
      )
      answer=resp.choices[0].message.content.strip()
    except Exception as e:
      print(f"[调用失败] {e}")
      continue

    stats["total"] += 1

    ok, bad = check_citations(answer, len(hits))
    refused = any(k in answer for k in
                  ["未找到相关依据", "建议咨询", "不属于劳动法", "不属于劳动",
                  "房屋租赁", "婚姻", "民间借贷"])  #命中一个就算TRUE

    print(f"答案：")
    for line in answer.split("\n"):
      if line.strip():
        print(f"{line}")
    print(f"是否拒答/说明范围：{'是' if refused else '否  可能在硬编'}")

    md += [f"### {q}", "", answer, "",
           f"是否拒答/说明范围：{'是' if refused else '否  可能在硬编'}", "",
           "人工判定： [ ] 正确拒答　[ ] 硬编了", "", "---", ""]

  #总结汇总
  print()
  print(f"成功调用：{stats['total']} 次（失败 {stats['failed_call']} 次）")
  print(f"引用校验：通过 {stats['cite_ok']} / 越界 {stats['cite_bad']}")
  print(f"检测到拒答：{stats['refused']} 次")

  md += ["## 汇总", "",
        f"- 成功调用：{stats['total']} 次（失败 {stats['failed_call']}）",
        f"- 引用校验：通过 {stats['cite_ok']} / 越界 {stats['cite_bad']}",
        f"- 检测到拒答：{stats['refused']} 次",
        "",
        "人工补充三个数字：",
        "",
        "1. 10 个问题里答案正确的有 ___ 个",
        "2. 检索失败的题里，模型编了 ___ 个，老实说未找到 ___ 个",
        "3. 3 个超范围问题里，拒答了 ___ 个",
        ""]  
  (EVAL / "easy_rag_result.md").write_text("\n".join(md), encoding="utf-8")
  print()

if __name__ == "__main__":
  main()


