"""
合并候选 + 应用规则 + 人工剔除 => 生成最终白名单

利用02产出：标题命中关键词与03产出：正文命中密度高）
先用自动规则：非劳动关系，正文密度<10%,法条数过少
随后，人工剔除，逐条写理由

"""
import json
from pathlib import Path

RAW = Path("data/raw")

# 排除"非劳动关系"，主体不是劳动人的
RULE_NON_LABOR = (
    r"公务员|军人|中国人民解放军|文职|监狱|罪犯|"
    r"安全生产|矿山安全|煤矿|中小学|勤工俭学"
)

#正文密度 < 10%
RULE_MIN_DENSITY = 0.10

#全文只有 1~2 条，检索价值低
RULE_MIN_ARTICLES = 3


#人工排除
EXCLUDE = {
    "中华人民共和国职业教育法":"职业技术教育，规定的是学校与培训，不是劳动关系",
    "中华人民共和国城镇集体所有制企业条例":"企业组织法，职工权益只在个别条款出现",
    "中华人民共和国残疾人保障法":"社会保障法，就业部分已由《残疾人就业条例》覆盖",
    "中华人民共和国船员条例":"船员资格与船舶管理，适用主体特殊",
    "中华人民共和国中外合作办学条例":"命中的是外籍教师聘用条款，非劳动关系",
    "对外劳务合作管理条例":"对外劳务经营的行政许可，非劳动者权益",
    "保安服务管理条例":"保安行业准入监管，非劳动关系",
    "中华人民共和国乡村集体所有制企业条例":"企业组织法，同城镇集体企业条例",
    "农民承担费用和劳务管理条例":"农民负担管理，非劳动关系",
    "中华人民共和国农业技术推广法":"农业技术推广，与劳动权益无关",
    "全国社会保障基金条例":"社保基金的投资运营，与个人社保待遇无关",
    "最高人民法院关于审理涉船员纠纷案件若干问题的规定":"船员特殊规定，适用面窄",
    "最高人民法院关于人民法院对经劳动争议仲裁裁决的纠纷准予撤诉"
    "或驳回起诉后劳动争议仲裁裁决从何时起生效的解释":"纯程序性解释，仅 3 条，检索价值低",
}


def main():
    kw = json.load(open(RAW / "_keyword_candidates.json", encoding="utf-8"))
    ct = json.load(open(RAW / "_content_candidates.json", encoding="utf-8"))

    #合并去重
    merged = {}     #meged={"id":{"id":xx,...}}
    for x in kw:
        merged[x["id"]] = {
            "id": x["id"], "title": x["title"],
            "articleCount": x["articleCount"],
            "density": None, "source": "keyword",
        }
    for x in ct:
        if x["id"] in merged:   #如果正文命中也在标题命中里，就标记为双向命中，并直接修改或添加三个字段
            merged[x["id"]]["source"] = "keyword+content"
            merged[x["id"]]["density"] = x["density"]
            merged[x["id"]]["hits"] = x["hits"]
        else:
            merged[x["id"]] = {
                "id": x["id"], "title": x["title"],
                "articleCount": x["articleCount"],
                "density": x["density"], "hits": x["hits"],
                "source": "content",
            }

    print(f"关键词候选: {len(kw)} 部")
    print(f"内容候选:   {len(ct)} 部")
    print(f"合并去重:   {len(merged)} 部")

    #自动规则
    import re
    non_labor = re.compile(RULE_NON_LABOR)  #非劳动关系的关键词

    #auto_dropped = []  #自动剔除的列表,stage1 = {}  #自动规则剔除后剩余的
    stage1, auto_dropped = {}, []
    #拿到merged的id与对于字典内容
    for lid, r in merged.items():
        if non_labor.search(r["title"]):
            auto_dropped.append((r["title"], "非劳动关系领域"))
        #密度太小
        elif r["source"] == "content" and (r["density"] or 0) < RULE_MIN_DENSITY:
            auto_dropped.append((r["title"], f"密度 {r['density']*100:.0f}% < 10%"))
        elif r["articleCount"] < RULE_MIN_ARTICLES:
            auto_dropped.append((r["title"], f"全文仅 {r['articleCount']} 条，没有检索价值的"))
        else:
            stage1[lid] = r
    print(f"自动规则剔除: {len(auto_dropped)} 部，剩 {len(stage1)} 部")

    #人工剔除
    #final = []  #最终白名单    manual_dropped = []  #人工剔除的列表
    final, manual_dropped = [], []
    for lid, r in stage1.items():
        if r["title"] in EXCLUDE:
            manual_dropped.append((r["title"], EXCLUDE[r["title"]]))# (title,理由)
        else:
            #添加保存理由字段
            tmp_map = {
                "keyword": "标题命中关键词",
                "content": "正文内容相关密度高（标题不含关键词）",
                "keyword+content": "标题与正文双向命中",
            }
            r["reason"] = tmp_map.get(r["source"])
            final.append(r)
    print(f"人工剔除:{len(manual_dropped)} 部，最终 {len(final)} 部")

    def final_sort_key(r):
        return (r["articleCount"])
    final.sort(key=final_sort_key,reverse=True)  #按法条数量倒序排列

    json.dump(final, open(RAW / "_selected.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    print()
    print("自动规则剔除:")
    for t, why in auto_dropped:
        print(f"{why} {t}")
    print()
    print("人工剔除")
    for t, why in manual_dropped:
        print(f"{t}\n-> {why}")
    print()
    print("最终白名单")
    for r in final:
        print(f"{r['articleCount']:>4}条  {r['title']}")
    print("-" * 56)
    print(f"合计: {len(final)} 部 / {sum(r['articleCount'] for r in final)} 条法条")


if __name__ == "__main__":
    main()

